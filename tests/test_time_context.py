"""The time block sent to Grok: ASCII UTC offset plus an IANA name only when it can be confirmed.

On Windows CPython names the local zone through the C runtime's strftime("%Z"), which can give '??????',
mojibake or lone surrogates for a localized name such as '中国标准时间'. None of that may reach the prompt.
"""
import json
from datetime import datetime, timedelta, timezone

import httpx
import pytest

from grok_search.providers import grok as grok_mod


def _zone_available(key: str) -> bool:
    try:
        from zoneinfo import ZoneInfo
        ZoneInfo(key)
        return True
    except Exception:
        return False


needs_tzdb = pytest.mark.skipif(
    not (_zone_available("Asia/Shanghai") and _zone_available("America/Los_Angeles")),
    reason="no IANA time zone database on this system",
)


def fake_datetime(name: str, offset: timedelta = timedelta(hours=8)):
    """datetime.now().astimezone() as CPython on Windows builds it: a fixed offset carrying the CRT's name."""
    fixed = datetime(2026, 10, 17, 8, 30, 5, tzinfo=timezone(offset, name))

    class _Naive(datetime):
        def astimezone(self, tz=None):
            return fixed if tz is None else fixed.astimezone(tz)

    class FakeDT(datetime):
        @classmethod
        def now(cls, tz=None):
            if tz is None:
                return _Naive(2026, 10, 17, 8, 30, 5)
            return fixed.astimezone(tz)

    return FakeDT


@pytest.fixture
def no_system_zone(monkeypatch, tmp_path):
    """No TZ, no /etc/localtime link, no /etc/timezone: only the offset can be reported."""
    monkeypatch.delenv("TZ", raising=False)
    monkeypatch.setattr(grok_mod, "_LOCALTIME_LINK", str(tmp_path / "missing-localtime"))
    monkeypatch.setattr(grok_mod, "_TIMEZONE_FILE", str(tmp_path / "missing-timezone"))
    return tmp_path


def timezone_line(block: str) -> str:
    return next(line for line in block.splitlines() if line.startswith("- Timezone:"))


@pytest.mark.parametrize("crt_name", ["中国标准时间", "??????", "\udcd6\udcd0", "ÖÐ\udc81ú", ""])
def test_localized_or_garbled_zone_names_never_reach_the_block(monkeypatch, no_system_zone, crt_name):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime(crt_name))
    block = grok_mod.get_local_time_info()
    assert timezone_line(block) == "- Timezone: UTC+08:00"
    assert "- Date: 2026-10-17 (星期六)" in block and "- Time: 08:30:05" in block
    # Only the weekday is non-ASCII, and it is generated by this code, not by the C runtime.
    assert block.replace("星期六", "").isascii()
    block.encode("utf-8")


@pytest.mark.parametrize("offset, expected", [
    (timedelta(hours=-3, minutes=-30), "UTC-03:30"),
    (timedelta(hours=5, minutes=45), "UTC+05:45"),
    (timedelta(0), "UTC+00:00"),
    (timedelta(hours=-10), "UTC-10:00"),
    (timedelta(hours=14), "UTC+14:00"),
])
def test_offsets_are_formatted_with_sign_hours_and_minutes(monkeypatch, no_system_zone, offset, expected):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime("zone", offset))
    assert timezone_line(grok_mod.get_local_time_info()) == f"- Timezone: {expected}"


@needs_tzdb
def test_tz_env_name_is_added_when_its_offset_matches(monkeypatch, no_system_zone):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime("中国标准时间"))
    monkeypatch.setenv("TZ", "Asia/Shanghai")
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC+08:00 (Asia/Shanghai)"
    monkeypatch.setenv("TZ", ":Asia/Shanghai")
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC+08:00 (Asia/Shanghai)"


@needs_tzdb
def test_zone_name_contradicting_the_offset_is_left_out(monkeypatch, no_system_zone):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime("中国标准时间"))
    monkeypatch.setenv("TZ", "America/Los_Angeles")
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC+08:00"


@pytest.mark.parametrize("tz_value", ["中国", "CST-8", "../../etc/passwd", "Asia/No_Such_Zone", "  "])
def test_unusable_tz_values_are_ignored(monkeypatch, no_system_zone, tz_value):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime("中国标准时间"))
    monkeypatch.setenv("TZ", tz_value)
    line = timezone_line(grok_mod.get_local_time_info())
    assert line == "- Timezone: UTC+08:00" and line.isascii()


@needs_tzdb
def test_localtime_symlink_and_timezone_file_are_used(monkeypatch, no_system_zone):
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime("Pacific", timedelta(hours=-7)))
    link = no_system_zone / "localtime"
    link.symlink_to("/usr/share/zoneinfo/America/Los_Angeles")
    monkeypatch.setattr(grok_mod, "_LOCALTIME_LINK", str(link))
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC-07:00 (America/Los_Angeles)"

    monkeypatch.setattr(grok_mod, "_LOCALTIME_LINK", str(no_system_zone / "missing"))
    tzfile = no_system_zone / "timezone"
    tzfile.write_text("America/Los_Angeles\n")
    monkeypatch.setattr(grok_mod, "_TIMEZONE_FILE", str(tzfile))
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC-07:00 (America/Los_Angeles)"


def test_broken_clock_falls_back_to_utc(monkeypatch, no_system_zone):
    class Broken(datetime):
        @classmethod
        def now(cls, tz=None):
            if tz is None:
                raise OSError("localtime failed")
            return datetime(2026, 10, 17, 0, 30, tzinfo=tz)

    monkeypatch.setattr(grok_mod, "datetime", Broken)
    assert timezone_line(grok_mod.get_local_time_info()) == "- Timezone: UTC+00:00"


@pytest.mark.asyncio
@pytest.mark.parametrize("crt_name", ["中国标准时间", "??????", "ÖÐ\udc81ú"])
async def test_request_body_carries_the_ascii_zone_and_encodes(monkeypatch, no_system_zone, crt_name):
    """v1.12.0 sent the CRT name verbatim; a lone surrogate in it made httpx raise UnicodeEncodeError."""
    monkeypatch.setattr(grok_mod, "datetime", fake_datetime(crt_name))
    captured = []

    def handler(request: httpx.Request) -> httpx.Response:
        captured.append(request.content)
        stream = (
            'data: {"choices":[{"delta":{"content":"ok"},"finish_reason":null}]}\n\n'
            'data: {"choices":[{"delta":{},"finish_reason":"stop"}]}\n\n'
            "data: [DONE]\n\n"
        )
        return httpx.Response(200, headers={"content-type": "text/event-stream"}, content=stream.encode())

    real_client = httpx.AsyncClient

    def client_factory(*args, **kwargs):
        kwargs["transport"] = httpx.MockTransport(handler)
        return real_client(*args, **kwargs)

    monkeypatch.setattr(grok_mod.httpx, "AsyncClient", client_factory)
    provider = grok_mod.GrokSearchProvider("https://api.example.test/v1", "test-key", "grok-4.7")
    result = await provider.search_with_sources("what time is it", platform="   ")
    assert result.content == "ok"
    body = json.loads(captured[0].decode("utf-8"))
    user = next(m["content"] for m in body["messages"] if m["role"] == "user")
    assert "- Timezone: UTC+08:00\n" in user
    assert crt_name not in user
    # A whitespace-only platform adds no "focus on these platform" line.
    assert "focus on these platform" not in user
